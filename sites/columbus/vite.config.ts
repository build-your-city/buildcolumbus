import { appendFileSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, URL } from "node:url";
import tailwindcss from "@tailwindcss/vite";
import { tanstackRouter } from "@tanstack/router-plugin/vite";
import viteReact from "@vitejs/plugin-react";
import { defineConfig } from "vite";
import {
	headTags,
	pageMetaHtml,
	withPageMeta,
} from "../../src/lib/headTags.ts";
import { pages, site } from "./config/site.ts";

/**
 * Build config for buildcolumbus.org. The site lives in this folder and
 * imports the shared library from the repo's src/ via the "@" alias.
 * Run with `npm run dev:columbus` / `npm run build:columbus`; the build
 * lands in dist/columbus/.
 */
const here = (p: string) => fileURLToPath(new URL(p, import.meta.url));
const outDir = here("../../dist/columbus");
const innerPages = Object.values(pages).filter((p) => p.path !== "/");

export default defineConfig({
	root: here("."),
	plugins: [
		tanstackRouter({
			target: "react",
			autoCodeSplitting: true,
			routesDirectory: here("./routes"),
			generatedRouteTree: here("./routeTree.gen.ts"),
		}),
		viteReact(),
		tailwindcss(),
		{
			// Stamp the site-wide tags (share image, icons, manifest) and the
			// home page's title, description, canonical, and share tags into
			// index.html, so crawlers that don't run JavaScript see them.
			name: "site-head-tags",
			transformIndexHtml: (html) => ({
				html: html.replace(
					"</head>",
					`${pageMetaHtml(site, pages.home)}\n  </head>`,
				),
				tags: headTags(site),
			}),
		},
		{
			// After a build, from the pages in config/site.ts:
			// - one HTML file per inner page (meetup.html, ...) with that page's
			//   own tags, so each URL gets its own share card;
			// - Netlify rewrites serving those files, and every other path
			//   with a real 404 status (the app renders its not-found page);
			// - sitemap.xml.
			name: "site-pages",
			apply: "build",
			closeBundle() {
				const index = readFileSync(`${outDir}/index.html`, "utf8");
				for (const page of innerPages) {
					writeFileSync(
						`${outDir}${page.path}.html`,
						withPageMeta(index, site, page),
					);
				}

				const rewrites = innerPages.map(
					(p) => `${p.path}  ${p.path}.html  200`,
				);
				appendFileSync(
					`${outDir}/_redirects`,
					[
						"",
						"# Generated by vite.config.ts from the pages in config/site.ts.",
						...rewrites,
						"/*  /index.html  404",
						"",
					].join("\n"),
				);

				const urls = Object.values(pages).map(
					(p) => `\t<url><loc>${site.url}${p.path}</loc></url>`,
				);
				writeFileSync(
					`${outDir}/sitemap.xml`,
					[
						'<?xml version="1.0" encoding="UTF-8"?>',
						'<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
						...urls,
						"</urlset>",
						"",
					].join("\n"),
				);
			},
		},
	],
	resolve: {
		alias: {
			"@": here("../../src"),
		},
	},
	build: {
		outDir,
		emptyOutDir: true,
	},
});
